/**
 * Industry Template Catalog
 * Each template defines CSS variables + layout + enabled components
 * Templates are snapshots — editing master does NOT break existing cards
 */

export interface IndustryTemplate {
  id: string;
  name: string;
  industry: string;
  industryGroup: string;
  description: string;
  font: string;
  headingFont: string;
  // CSS variables
  background: string;       // --theme-background
  surface: string;          // --theme-surface
  primary: string;          // --theme-primary
  secondary: string;        // --theme-secondary
  accent: string;           // --theme-accent
  text: string;             // --theme-text
  muted: string;            // --theme-muted
  border: string;           // --theme-border
  // Style tokens
  buttonStyle: 'filled' | 'outlined' | 'soft' | 'pill' | 'glass';
  cardStyle: 'flat' | 'soft' | 'glass' | 'bordered';
  borderRadius: string;
  headerStyle: 'centered' | 'left' | 'hero' | 'cover' | 'minimal' | 'split';
  avatarShape: 'circle' | 'rounded' | 'square';
  animation: 'none' | 'subtle' | 'smooth';
  // Enabled components (ordered)
  enabledComponents: string[];
  // Locks
  allowColorCustomization: boolean;
  allowFontCustomization: boolean;
  isPublished: boolean;
  isRecommended: boolean;
  tags: string[];
}

