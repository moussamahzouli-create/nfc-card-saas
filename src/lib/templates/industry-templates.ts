// ─── HELPER FUNCTIONS ────────────────────────────────────────

export function getTemplateById(id: string): IndustryTemplate | undefined {
  return INDUSTRY_TEMPLATES.find(t => t.id === id);
}

export function getTemplatesByIndustry(industry: string): IndustryTemplate[] {
  return INDUSTRY_TEMPLATES.filter(t =>
    t.industry.toLowerCase().includes(industry.toLowerCase()) ||
    t.industryGroup.toLowerCase().includes(industry.toLowerCase())
  );
}

export function getRecommendedTemplates(industryGroup?: string): IndustryTemplate[] {
  return INDUSTRY_TEMPLATES.filter(t =>
    t.isPublished && (industryGroup ? t.industryGroup === industryGroup : t.isRecommended)
  );
}

export function templateToCssVars(tpl: IndustryTemplate): Record<string, string> {
  return {
    '--theme-background': tpl.background,
    '--theme-surface':    tpl.surface,
    '--theme-primary':    tpl.primary,
    '--theme-secondary':  tpl.secondary,
    '--theme-accent':     tpl.accent,
    '--theme-text':       tpl.text,
    '--theme-muted':      tpl.muted,
    '--theme-border':     tpl.border,
    '--theme-radius':     tpl.borderRadius,
    '--theme-font':       tpl.font,
    '--theme-heading-font': tpl.headingFont,
  };
}
